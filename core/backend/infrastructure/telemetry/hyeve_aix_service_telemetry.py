def setup_structlog() -> None:
    """Configure structlog to emit JSON structured logs."""
    structlog.configure(
        processors=[
            structlog.processors.add_log_level,
            structlog.processors.TimeStamper(fmt="iso"),
            structlog.processors.JSONRenderer(),
        ],
        wrapper_class=structlog.make_filtering_bound_logger(logging.INFO),
        cache_logger_on_first_use=True,
    )
    logging.basicConfig(
        level=getattr(logging, settings.LOG_LEVEL.upper(), logging.INFO),
        stream=sys.stdout,
        format="%(message)s",
    )


def setup_tracing(app: FastAPI) -> Tracer | None:
    """Initialise OpenTelemetry tracing if the SDK is installed."""
    try:
        from opentelemetry import trace
        from opentelemetry.exporter.jaeger.thrift import JaegerExporter
        from opentelemetry.instrumentation.fastapi import FastAPIInstrumentor
        from opentelemetry.sdk.trace import TracerProvider
        from opentelemetry.sdk.trace.export import BatchSpanProcessor

        provider = TracerProvider()
        provider.add_span_processor(BatchSpanProcessor(JaegerExporter(agent_host_name="jaeger", agent_port=6831)))
        trace.set_tracer_provider(provider)

        # Instrument FastAPI
        FastAPIInstrumentor.instrument_app(app=app, server_request_hook=None, client_request_hook=None)

        return trace.get_tracer("hyeve_aix_service")
    except Exception:  # pragma: no cover - optional dependency
        structlog.get_logger("hyeve_aix_service.tracing").info("tracing.disabled", reason="opentelemetry unavailable")
        return None


def setup_sentry() -> None:
    """Initialise Sentry SDK if configured."""
    dsn = getattr(settings, "SENTRY_DSN", None)
    if not dsn or sentry_sdk is None:  # pragma: no cover - configuration dependent
        return
    try:
        sentry_sdk.init(
            dsn=dsn,
            environment=getattr(settings, "SENTRY_ENVIRONMENT", getattr(settings, "ENVIRONMENT", "local")),
            traces_sample_rate=getattr(settings, "SENTRY_SAMPLE_RATE", 0.1),
            integrations=[FastApiIntegration()],
        )
        structlog.get_logger("hyeve_aix_service.telemetry").info("sentry.initialised")
    except Exception as exc:  # pragma: no cover - defensive path
        structlog.get_logger("hyeve_aix_service.telemetry").warning("sentry.initialisation_failed", error=str(exc))


