class RequestLoggingMiddleware(BaseHTTPMiddleware):
    """Structured logging wrapper that also updates request metrics."""

    def __init__(self, app, exclude_paths: tuple[str, ...] | None = None) -> None:
        super().__init__(app)
        self._exclude_paths = set(exclude_paths or ("/health", "/metrics"))
        self._logger = structlog.get_logger("hyeve_aix_service.middleware.request")

    async def dispatch(self, request: Request, call_next):
        if request.url.path in self._exclude_paths:
            return await call_next(request)

        start = time.perf_counter()
        client_ip = request.headers.get(
            "x-forwarded-for",
            request.client.host if request.client else "unknown",
        )
        self._logger.info(
            "request.started",
            method=request.method,
            path=request.url.path,
            client_ip=client_ip,
            **_request_context(request),
        )

        try:
            response = await call_next(request)
        except Exception as exc:  # pragma: no cover - observability path
            duration = time.perf_counter() - start
            ERROR_COUNT.labels(request.method, request.url.path, type(exc).__name__).inc()
            self._logger.exception(
                "request.failed",
                method=request.method,
                path=request.url.path,
                client_ip=client_ip,
                duration_ms=round(duration * 1000, 2),
                **_request_context(request),
            )
            raise

        duration = time.perf_counter() - start
        REQUEST_COUNT.labels(request.method, request.url.path, str(response.status_code)).inc()
        REQUEST_LATENCY.labels(request.method, request.url.path).observe(duration)
        self._logger.info(
            "request.completed",
            method=request.method,
            path=request.url.path,
            status=response.status_code,
            duration_ms=round(duration * 1000, 2),
            client_ip=client_ip,
            **_request_context(request),
        )
        return response


class PerformanceMonitoringMiddleware(BaseHTTPMiddleware):
    """Observes application latency and raises warnings for slow requests."""

    def __init__(self, app, slow_request_threshold: float = 1.0) -> None:
        super().__init__(app)
        self._threshold = slow_request_threshold
        self._logger = structlog.get_logger("hyeve_aix_service.middleware.performance")

    async def dispatch(self, request: Request, call_next):
        start = time.perf_counter()
        response = await call_next(request)
        duration = time.perf_counter() - start
        if duration >= self._threshold:
            self._logger.warning(
                "request.slow",
                method=request.method,
                path=request.url.path,
                duration=duration,
            )
        return response


