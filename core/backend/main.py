def _validate_public_router_authority_matrix(
    matrix: dict = PUBLIC_ROUTER_AUTHORITY_MATRIX,
) -> None:
    """Fail closed if mounted router authority coverage or retirement policy drifts."""
    mounted_router_names = {
        name
        for name, value in globals().items()
        if name.endswith("_router") and hasattr(value, "routes")
    }
    matrix_router_names = set(matrix["routers"])
    if mounted_router_names != matrix_router_names:
        missing = sorted(mounted_router_names - matrix_router_names)
        unexpected = sorted(matrix_router_names - mounted_router_names)
        raise RuntimeError(
            "PUBLIC_ROUTER_AUTHORITY_MATRIX does not cover mounted routers: "
            f"missing={missing}, unexpected={unexpected}"
        )

    canonical_writers = [
        name
        for name, authority in matrix["routers"].items()
        if authority == "CANONICAL_COMMAND"
    ]
    if len(canonical_writers) != 1 or canonical_writers[0] != "objective_cycle_router":
        raise RuntimeError(
            "objective_cycle_router must be the sole CANONICAL_COMMAND product writer"
        )

    for route_name, route_metadata in matrix["retired_mutation_routes"].items():
        if (
            route_metadata["status"] != "RETIRE"
            or route_metadata["mounted"] is not False
            or route_metadata.get("expected_http_status") != 410
        ):
            raise RuntimeError(
                f"Retired mutation route is not fail-closed with HTTP 410: {route_name}"
            )


_validate_public_router_authority_matrix()


