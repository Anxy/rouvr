_original_openapi = app.openapi


def _aix_openapi() -> dict:
    if app.openapi_schema:
        return app.openapi_schema
    schema = _original_openapi()
    schema["x-error-codes"] = _AIX_ERROR_CODES
    schema["x-public-router-authority-matrix"] = PUBLIC_ROUTER_AUTHORITY_MATRIX
    annotate_openapi_inclusion_classes(schema)
    app.openapi_schema = schema
    return schema


