"""FL-A1: OpenAPI snapshot + typed client regression tests.

- Committed web/src/lib/api/openapi.json matches the live FastAPI spec.
- web/src/lib/api/schema.d.ts is genuine openapi-typescript output covering
  every live path.
- The client wrapper binds the generated schema; no hand-written fetch/XHR
  to API routes exists outside web/src/lib/api/.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "web" / "src"
API_DIR = SRC / "lib" / "api"
OPENAPI_JSON = API_DIR / "openapi.json"
SCHEMA_TS = API_DIR / "schema.d.ts"
CLIENT_TS = API_DIR / "client.ts"
EXPORT_SCRIPT = ROOT / "scripts" / "export-openapi.py"

_FETCH_RE = re.compile(r"(?<![\w$.])fetch\s*\(")


def _live_spec():
    from ledger.app import make_app

    return make_app("sqlite:///:memory:").openapi()


def test_committed_openapi_matches_live_spec():
    assert OPENAPI_JSON.is_file(), "snapshot missing: run scripts/export-openapi.py"
    committed = json.loads(OPENAPI_JSON.read_text())
    assert committed == _live_spec()


def test_export_check_gate_is_green():
    proc = subprocess.run(
        [sys.executable, str(EXPORT_SCRIPT), "--check"],
        capture_output=True, text=True, cwd=ROOT,
    )
    assert proc.returncode == 0, proc.stderr or proc.stdout


def test_schema_is_generated_and_covers_live_paths():
    assert SCHEMA_TS.is_file(), "run pnpm --filter web gen:api"
    text = SCHEMA_TS.read_text()
    assert "auto-generated by openapi-typescript" in text
    missing = [p for p in _live_spec()["paths"] if f'"{p}"' not in text]
    assert not missing, f"schema.d.ts missing live paths: {missing}"


def test_client_wrapper_is_typed_against_schema():
    text = CLIENT_TS.read_text()
    assert re.search(r"from\s+[\"']\./schema[\"']", text)
    assert "openapi-fetch" in text and "paths" in text


def test_no_handwritten_fetch_outside_generated_client():
    offenders = []
    for f in sorted(SRC.rglob("*.ts")) + sorted(SRC.rglob("*.tsx")):
        if API_DIR in f.parents:
            continue
        body = f.read_text()
        if _FETCH_RE.search(body) or "XMLHttpRequest" in body:
            offenders.append(str(f.relative_to(ROOT)))
    assert not offenders, f"hand-written fetch outside web/src/lib/api/: {offenders}"
