"""FL-A1: OpenAPI snapshot + typed TS client regression tests.

- Committed web/src/lib/api/openapi.json covers exactly the live FastAPI
  routes (structural: path + method sets, immune to formatter drift).
- web/src/lib/api/schema.d.ts is genuine openapi-typescript output covering
  every live path.
- The client wrapper binds the generated schema.
- No hand-written fetch/XHR to API routes exists anywhere under web/src:
  screens import from web/src/lib/api instead.
"""
import contextlib
import json
import os
import re
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "web" / "src"
API_DIR = SRC / "lib" / "api"
OPENAPI_JSON = API_DIR / "openapi.json"
SCHEMA_TS = API_DIR / "schema.d.ts"
CLIENT_TS = API_DIR / "client.ts"

# A real fetch( call: not part of an identifier/member access (openapi-fetch
# imports and client.GET/POST helpers must not match).
_FETCH_RE = re.compile(r"(?<![\w$.])fetch\s*\(")


def _live_spec():
    sys.path.insert(0, str(ROOT))
    fd, tmp = tempfile.mkstemp(prefix="rouvr-openapi-test-", suffix=".db")
    os.close(fd)
    try:
        from ledger.app import make_app

        return make_app(f"sqlite:///{tmp}").openapi()
    finally:
        for suffix in ("", "-wal", "-shm"):
            with contextlib.suppress(OSError):
                os.unlink(tmp + suffix)


def _methods(spec: dict) -> dict:
    return {p: sorted(op for op in ops if op != "parameters")
            for p, ops in spec.get("paths", {}).items()}


def test_committed_openapi_covers_live_routes():
    assert OPENAPI_JSON.is_file(), "snapshot missing: run scripts/export_openapi.py"
    committed = json.loads(OPENAPI_JSON.read_text())
    live = _live_spec()
    assert _methods(committed) == _methods(live)


def test_schema_is_generated_and_covers_live_paths():
    assert SCHEMA_TS.is_file(), "run pnpm --filter web gen:api"
    text = SCHEMA_TS.read_text()
    assert "auto-generated by openapi-typescript" in text
    missing = [p for p in _live_spec()["paths"] if p not in text]
    assert not missing, f"schema.d.ts missing live paths: {missing}"


def test_client_wrapper_is_typed_against_schema():
    text = CLIENT_TS.read_text()
    assert re.search(r"from\s+[\"']\./schema[\"']", text)
    assert "openapi-fetch" in text and "paths" in text


def test_no_handwritten_fetch_to_api_routes():
    offenders = []
    for f in sorted(SRC.rglob("*.ts")) + sorted(SRC.rglob("*.tsx")):
        try:
            body = f.read_text()
        except UnicodeDecodeError:
            continue
        if _FETCH_RE.search(body) or "XMLHttpRequest" in body:
            offenders.append(str(f.relative_to(ROOT)))
    assert not offenders, f"hand-written fetch/XHR under web/src: {offenders}"
