"""FL-A1: OpenAPI + typed client stays generated, typed, and sole API path.

- Committed web/openapi.json matches the live FastAPI OpenAPI spec.
- web/src/lib/api/ holds openapi-typescript output plus a typed wrapper.
- No hand-written fetch/XHR to API routes outside web/src/lib/api/.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WEB = ROOT / "web"
SRC = WEB / "src"
API_DIR = SRC / "lib" / "api"
OPENAPI_JSON = WEB / "openapi.json"

_FETCH_RE = re.compile(r"(?<![\w$.])fetch\s*\(")


def _live_spec():
    import os

    os.environ.setdefault("ROUVR_INSECURE_DEV", "1")
    from ledger.app import make_app

    app = make_app("sqlite:///:memory:")
    return app.openapi()


def test_committed_openapi_matches_live_spec():
    assert OPENAPI_JSON.is_file(), "web/openapi.json missing: run scripts/export_openapi.py"
    committed = json.loads(OPENAPI_JSON.read_text())
    live = _live_spec()
    assert committed == live


def test_generated_client_typings_cover_ledger_paths():
    schema = API_DIR / "schema.d.ts"
    assert schema.is_file(), "generated web/src/lib/api/schema.d.ts missing"
    text = schema.read_text()
    assert "auto-generated by openapi-typescript" in text
    for path in ("/health", "/v1/tasks", "/v1/tasks/{tid}/transition",
                 "/v1/knowledge/search", "/v1/grants/active"):
        assert path in text, f"{path} missing from generated schema"


def test_client_wrapper_is_typed_against_schema():
    client = API_DIR / "client.ts"
    assert client.is_file(), "web/src/lib/api/client.ts missing"
    text = client.read_text()
    assert re.search(r"from\s+[\"']\./schema[\"']", text), "client must import generated ./schema types"
    assert "paths" in text, "client must bind the generated paths type"


def test_no_handwritten_fetch_outside_generated_client():
    offenders = []
    for f in sorted(SRC.rglob("*.ts")) + sorted(SRC.rglob("*.tsx")):
        if API_DIR in f.parents:
            continue
        try:
            body = f.read_text()
        except UnicodeDecodeError:
            continue
        if _FETCH_RE.search(body) or "XMLHttpRequest" in body:
            offenders.append(str(f.relative_to(ROOT)))
    assert not offenders, f"hand-written fetch outside web/src/lib/api/: {offenders}"
